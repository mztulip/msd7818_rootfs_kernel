#!/usr/bin/env python3
"""Generate font.h (16x32 bitmap font, ASCII 32..126) for bootsel.

Renders DejaVu Sans Mono Bold with Pillow. DejaVu fonts are under the
Bitstream Vera license with DejaVu changes in the public domain, which
allows using and redistributing derived bitmaps.

Usage: mkfont.py [TTF] > font.h
"""
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 16, 32
TTF = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf'


def main():
    size = 26
    font = ImageFont.truetype(TTF, size)
    asc, desc = font.getmetrics()
    top = (H - (asc + desc)) // 2
    out = ['/* Generated by mkfont.py from DejaVu Sans Mono Bold (Bitstream Vera license). */',
           '/* 16x32 glyphs for ASCII 32..126, one uint16_t per row, bit 15 = left pixel. */',
           '#define FONT_W %d' % W, '#define FONT_H %d' % H,
           'static const uint16_t font[95][%d] = {' % H]
    for ch in range(32, 127):
        img = Image.new('L', (W, H), 0)
        d = ImageDraw.Draw(img)
        w = d.textlength(chr(ch), font=font)
        d.text(((W - w) / 2, top), chr(ch), font=font, fill=255)
        rows = []
        for y in range(H):
            v = 0
            for x in range(W):
                if img.getpixel((x, y)) >= 110:
                    v |= 0x8000 >> x
            rows.append('0x%04x' % v)
        out.append('\t{ %s },\t/* %r */' % (', '.join(rows), chr(ch)))
    out.append('};')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
