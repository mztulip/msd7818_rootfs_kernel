#!/usr/bin/env python3
"""Turn the assembled own SE program (pcm.hex from tools/dsp/pcm.s, 24-bit words) into own_pcm_prog.h
for own_audio.h. Our own code (no MStar DSP code), so the header may be published.

Usage: gen_own_pcm.py [PCM.hex] [OUT.h]
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
default = os.path.join(here, '../dsp/pcm.hex')		# public repo layout (tools/dsp)
if not os.path.exists(default):
    default = os.path.join(here, '../../dsp_re/own/pcm.hex')	# working tree
src = sys.argv[1] if len(sys.argv) > 1 else default
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'own_pcm_prog.h')
words = [int(w, 16) for w in open(src).read().split()]
with open(dst, 'w') as f:
    f.write('/* own_pcm_prog.h - generated by gen_own_pcm.py from pcm.hex (asm.py of pcm.s, in\n'
            ' * tools/dsp): our own SE DSP program for own_audio.h, %d words. */\n' % len(words))
    f.write('static const uint32_t own_pcm_prog[] = {\n')
    for i in range(0, len(words), 8):
        f.write('\t' + ' '.join('0x%06x,' % w for w in words[i:i + 8]) + '\n')
    f.write('};\n')
print('%s: %d words' % (dst, len(words)))
